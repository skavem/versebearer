// Package search реализует полнотекстовый поиск по стихам и куплетам поверх
// Bleve с морфологией русского языка.
//
// # Почему «двустороннее расширение», а не лемматизация
//
// Обычный подход — привести слово к начальной форме (лемме) и при индексации,
// и в запросе. Для русского это требует морфоанализатора; единственный на Go —
// gomorphy (словарь OpenCorpora) — леммы не отдаёт вовсе: у него есть только
// WordForms(слово) — все формы парадигмы. И эта функция НЕ инвариантна
// относительно входной формы: WordForms("любовь") возвращает парадигму без
// формы "любви" (анализатор выбирает один «лучший» разбор и теряет остальные),
// тогда как WordForms("любви") форму "любовь" содержит. Любая схема вида
// «канонический ключ парадигмы» на этом ломается — причём на слове "любовь",
// одном из самых частых в Библии.
//
// Поэтому здесь расширение применяется СИММЕТРИЧНО: и к слову текста при
// индексации, и к слову запроса. Слово превращается в набор снежковых стемм
// всех своих словоформ (Expand). Совпадением считается непустое пересечение
// наборов. Асимметрия gomorphy при этом перестаёт вредить: даже если
// раскрытие "любовь" не дало "любви", раскрытие "любви" дало "любовь", и
// наборы пересекаются по стемме "любов".
//
// Снежок (стеммер) поверх словоформ нужен, чтобы схлопнуть остаточные различия
// внутри парадигмы и дать деградацию для слов, которых нет в словаре
// (библейские имена, архаизмы вроде «рече») — для них Expand возвращает
// одну лишь собственную стемму слова, то есть поиск скатывается к обычному
// стеммингу, а не ломается.
//
// Замеренный охват на контрольных парах «что вводит оператор» → «что стоит в
// тексте»: 14/16. Непокрытыми остаются «говорить»→«сказал» и
// «верить»→«уверовал» — это супплетивы и словообразование, морфологией они не
// решаются в принципе, только словарём синонимов.
package search

import (
	"regexp"
	"strings"
	"sync"
	"unicode/utf8"

	"github.com/jus1d/gomorphy"
	"github.com/kljensen/snowball/russian"
	"golang.org/x/text/unicode/norm"
)

// wordRe вырезает слова из текста. Диакритика (\p{M}) включена намеренно:
// в некоторых переводах буквы записаны разложенно (например «й» как
// «и» + U+0306), и без \p{M} слово порвалось бы пополам. Normalize ниже
// такие последовательности схлопывает обратно.
var wordRe = regexp.MustCompile(`[\p{L}\p{M}]+`)

var (
	analyzer     *gomorphy.Analyzer
	analyzerOnce sync.Once

	// expandCache кэширует раскрытие словоформ. Словарь живой текст переиспользует
	// очень плотно: на 200 тыс. слов Библии приходится ~19 тыс. уникальных, так
	// что кэш срезает почти всю работу. Значения неизменяемы после записи.
	expandCache   = map[string][]string{}
	expandCacheMu sync.RWMutex
)

// initAnalyzer лениво поднимает словарь OpenCorpora (~30 мс, ~8.8 МБ в
// бинарнике). Ошибка загрузки не фатальна: analyzer остаётся nil, и Expand
// деградирует до чистого стемминга.
func initAnalyzer() {
	analyzerOnce.Do(func() {
		a, err := gomorphy.Default()
		if err != nil {
			return
		}
		analyzer = a
	})
}

// Normalize приводит текст к форме, в которой его сравнивают: NFC (склеивает
// разложенные «й»/«ё» обратно в одну руну), нижний регистр и ё→е.
//
// NFC обязателен: в Открытой Библии часть букв записана разложенно, и без
// нормализации поиск по обычному русскому слову промахивается мимо визуально
// идентичного текста. Свёртка ё→е нужна в обе стороны — в словаре OpenCorpora
// «шёл» есть, а «шел» нет, при этом в текстах переводов встречается и то и то.
func Normalize(s string) string {
	s = norm.NFC.String(s)
	s = strings.ToLower(s)
	return strings.ReplaceAll(s, "ё", "е")
}

// Expand раскрывает нормализованное слово в набор стемм всех его словоформ.
// Всегда содержит собственную стемму слова, поэтому для слов вне словаря
// (имена собственные, архаизмы) возвращает набор из одного элемента.
func Expand(word string) []string {
	expandCacheMu.RLock()
	cached, ok := expandCache[word]
	expandCacheMu.RUnlock()
	if ok {
		return cached
	}

	initAnalyzer()

	set := map[string]bool{russian.Stem(word, false): true}
	if analyzer != nil {
		// Словарь знает «шёл», а на входе после Normalize всегда «шел» —
		// спрашиваем оба варианта, иначе теряется вся ё-содержащая лексика.
		for _, probe := range eVariants(word) {
			for _, form := range analyzer.WordForms(probe) {
				set[russian.Stem(strings.ToLower(form), false)] = true
			}
		}
	}

	out := make([]string, 0, len(set))
	for stem := range set {
		out = append(out, stem)
	}

	expandCacheMu.Lock()
	expandCache[word] = out
	expandCacheMu.Unlock()
	return out
}

// eVariants возвращает слово и, если в нём есть «е», вариант с «ё» в каждой
// позиции по очереди — восстановить настоящее место «ё» без словаря нельзя,
// поэтому пробуем все. Слов с «е» больше одного-двух вхождений немного, а
// промах по словарю стоит дороже лишнего запроса.
func eVariants(word string) []string {
	out := []string{word}
	if !strings.Contains(word, "е") {
		return out
	}
	runes := []rune(word)
	for i, r := range runes {
		if r != 'е' {
			continue
		}
		variant := make([]rune, len(runes))
		copy(variant, runes)
		variant[i] = 'ё'
		out = append(out, string(variant))
		if len(out) > 4 { // защита от слов вроде «переселение» — дальше отдача падает
			break
		}
	}
	return out
}

// ExpandText превращает текст в строку стемм через пробел — то, что уходит в
// морфологическое поле индекса. Порядок слов сохраняется, дубли внутри одного
// слова убраны, но повторы по тексту оставлены: на них считается частота для
// BM25.
func ExpandText(text string) string {
	var b strings.Builder
	for _, word := range wordRe.FindAllString(Normalize(text), -1) {
		for _, stem := range Expand(word) {
			b.WriteString(stem)
			b.WriteByte(' ')
		}
	}
	return b.String()
}

// QueryTerms раскрывает запрос в набор стемм для поиска по морфологическому
// полю. Возвращает по одному набору на слово запроса: слова соединяются
// конъюнкцией (нужны все), стеммы внутри слова — дизъюнкцией (годится любая).
func QueryTerms(query string) [][]string {
	words := wordRe.FindAllString(Normalize(query), -1)
	out := make([][]string, 0, len(words))
	for _, word := range words {
		out = append(out, Expand(word))
	}
	return out
}

// Match — вхождение слова запроса в текст: смещение и длина в СИМВОЛАХ
// (рунах) исходной, ненормализованной строки.
//
// Не в байтах: эти позиции уходят в JS, где строка режется по code units
// UTF-16, а кириллическая буква занимает два байта UTF-8 и одну единицу
// UTF-16. Весь текст переводов лежит в BMP (кириллица, латиница, знаки,
// комбинирующие диакритики), где руна и code unit совпадают один в один, —
// поэтому рунные смещения фронт может применять к строке напрямую.
type Match struct {
	Start int `json:"start"`
	Len   int `json:"len"`
}

// Highlight находит в оригинальном тексте слова, морфологически совпадающие с
// запросом.
//
// Подсветка считается здесь, а не средствами Bleve, намеренно: индекс хранит
// стеммы, и bleve-хайлайтер подсветил бы стеммы («возлюб») вместо живого слова
// («возлюбил»). Здесь же исходный текст остаётся нетронутым, а совпадение
// определяется тем же пересечением наборов, что и в самом поиске, — то есть
// подсветка не может разойтись с выдачей.
func Highlight(text string, terms [][]string) []Match {
	if len(terms) == 0 {
		return nil
	}

	wanted := make(map[string]bool)
	for _, stems := range terms {
		for _, stem := range stems {
			wanted[stem] = true
		}
	}

	// Токенизируется ИСХОДНЫЙ текст, а нормализуется каждое слово по
	// отдельности — только так смещения остаются валидными для строки, которую
	// получит фронт. Нормализовать текст целиком нельзя: NFC схлопывает
	// разложенные последовательности («и» + U+0306 → «й»), то есть меняет длину
	// строки, и все последующие позиции уезжают.
	var out []Match
	// Байтовые границы, которые отдаёт регулярное выражение, переводятся в
	// рунные одним проходом: границы идут по возрастанию, поэтому счётчик рун
	// достаточно двигать вперёд.
	runeIdx, byteIdx := 0, 0
	advance := func(to int) int {
		for byteIdx < to {
			_, size := utf8.DecodeRuneInString(text[byteIdx:])
			byteIdx += size
			runeIdx++
		}
		return runeIdx
	}

	for _, loc := range wordRe.FindAllStringIndex(text, -1) {
		word := Normalize(text[loc[0]:loc[1]])
		matched := false
		for _, stem := range Expand(word) {
			if wanted[stem] {
				matched = true
				break
			}
		}
		if !matched {
			continue
		}
		start := advance(loc[0])
		end := advance(loc[1])
		out = append(out, Match{Start: start, Len: end - start})
	}
	return out
}
